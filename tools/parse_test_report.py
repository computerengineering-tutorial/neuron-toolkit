#!/usr/bin/env python3
"""parse_test_report.py - Deep JSON report parser for pytest test suites.

Parses report.json generated by `pytest --json-report --json-report-file=report.json`
to extract, group, and analyze test failures, exceptions, and warnings.

Usage:
    python3 tools/parse_test_report.py [report.json]
    python3 tools/parse_test_report.py --full
    python3 tools/parse_test_report.py --filter "vulnerabilities"
    python3 tools/parse_test_report.py --failures-only
    python3 tools/parse_test_report.py --warnings-only
    python3 tools/parse_test_report.py --json-out failures_summary.json
"""

from __future__ import annotations

import argparse
import collections
import json
import os
import re
import sys
from typing import Any, Dict, List, Optional


# ANSI styling
class Style:
    BOLD = "\033[1m"
    DIM = "\033[2m"
    RED = "\033[31m"
    GREEN = "\033[32m"
    YELLOW = "\033[33m"
    BLUE = "\033[34m"
    MAGENTA = "\033[35m"
    CYAN = "\033[36m"
    RESET = "\033[0m"

    @classmethod
    def strip_if_no_color(cls, enabled: bool):
        if not enabled:
            for attr in dir(cls):
                if not attr.startswith("__") and isinstance(getattr(cls, attr), str):
                    setattr(cls, attr, "")


def load_report(filepath: str) -> Dict[str, Any]:
    """Load and validate pytest json-report file."""
    if not os.path.exists(filepath):
        sys.stderr.write(f"Error: Report file '{filepath}' does not exist.\n")
        sys.stderr.write("Run: pytest --json-report --json-report-file=report.json\n")
        sys.exit(1)

    try:
        with open(filepath, "r", encoding="utf-8") as f:
            return json.load(f)
    except json.JSONDecodeError as e:
        sys.stderr.write(f"Error decoding JSON from '{filepath}': {e}\n")
        sys.exit(1)


def categorize_failure(crash_msg: str) -> str:
    """Categorize failure by root cause type."""
    if "ValidationError" in crash_msg:
        if "num_outputs" in crash_msg or "Split" in crash_msg:
            return "ONNX OpSet Schema Mismatch (Split/num_outputs)"
        if "No opset import for domain" in crash_msg:
            return "Missing Custom Domain Opset Import"
        if "topologically sorted" in crash_msg:
            return "Topological DAG Sorting Inversion"
        return "ONNX Schema / Spec Validation Error"
    if "AssertionError" in crash_msg:
        if "valid C identifier" in crash_msg:
            return "Identifier Syntax / C Identifier Violation"
        if "id(" in crash_msg or "Expected 19 nodes, got 21" in crash_msg:
            return "Memory Pointer Aliasing / Node Drop Collision"
        if "Expected Add producer first" in crash_msg:
            return "Function Internal Producer/Consumer Ordering"
        return "Compiler Assertion Failure"
    if "TypeError" in crash_msg or "AttributeError" in crash_msg:
        return "Interface / Type API Error"
    return "Runtime Exception"


def format_duration(seconds: float) -> str:
    """Format duration in s or ms."""
    if seconds < 1.0:
        return f"{seconds * 1000:.1f}ms"
    return f"{seconds:.2f}s"


def print_summary_header(data: Dict[str, Any], filepath: str) -> None:
    """Print executive dashboard header."""
    summary = data.get("summary", {})
    duration = data.get("duration", 0.0)
    exitcode = data.get("exitcode", 0)
    created = data.get("created", 0)

    total = summary.get("total", summary.get("collected", 0))
    passed = summary.get("passed", 0)
    failed = summary.get("failed", 0)
    skipped = summary.get("skipped", 0)
    warnings = len(data.get("warnings", []))

    pass_rate = (passed / total * 100) if total > 0 else 0.0

    print("=" * 80)
    print(f"{Style.BOLD}{Style.CYAN}PYTEST EXECUTION REPORT SUMMARY{Style.RESET} : {Style.BOLD}{filepath}{Style.RESET}")
    print("=" * 80)
    print(f"  {Style.BOLD}Duration:{Style.RESET}   {format_duration(duration):<15}  {Style.BOLD}Exit Code:{Style.RESET}  {exitcode}")
    print(f"  {Style.BOLD}Total Tests:{Style.RESET}{total:<15}  {Style.BOLD}Pass Rate:{Style.RESET}  {pass_rate:.1f}%")
    print(
        f"  {Style.GREEN}{Style.BOLD}PASSED:{Style.RESET}    {passed:<15}  "
        f"{Style.RED}{Style.BOLD}FAILED:{Style.RESET}    {failed:<15}  "
        f"{Style.YELLOW}{Style.BOLD}SKIPPED:{Style.RESET}   {skipped:<10}"
    )
    print(f"  {Style.YELLOW}{Style.BOLD}WARNINGS:{Style.RESET}  {warnings}")
    print("=" * 80)


def analyze_failures(
    tests: List[Dict[str, Any]],
    filter_pattern: Optional[str] = None,
    show_full: bool = False,
) -> List[Dict[str, Any]]:
    """Analyze and display failed tests in detail."""
    failed_tests = [t for t in tests if t.get("outcome") == "failed"]

    if filter_pattern:
        pat = filter_pattern.lower()
        failed_tests = [
            t for t in failed_tests
            if pat in t.get("nodeid", "").lower()
            or pat in t.get("call", {}).get("crash", {}).get("message", "").lower()
        ]

    print(f"\n{Style.BOLD}{Style.RED}▶ FAILED TESTCASES ANALYSIS ({len(failed_tests)} failures){Style.RESET}")
    print("-" * 80)

    if not failed_tests:
        print(f"  {Style.GREEN}✔ No matching failed testcases!{Style.RESET}\n")
        return []

    # Group by file
    by_file: Dict[str, List[Dict[str, Any]]] = collections.defaultdict(list)
    for t in failed_tests:
        nodeid = t.get("nodeid", "")
        file_part = nodeid.split("::")[0] if "::" in nodeid else nodeid
        by_file[file_part].append(t)

    structured_failures = []

    count = 0
    for file_name, file_tests in by_file.items():
        print(f"\n{Style.BOLD}{Style.MAGENTA}📁 {file_name}{Style.RESET} ({len(file_tests)} failure{'s' if len(file_tests) > 1 else ''})")
        print("  " + "·" * 76)

        for t in file_tests:
            count += 1
            nodeid = t.get("nodeid", "")
            test_name = nodeid.split("::")[-1] if "::" in nodeid else nodeid

            # Locate stage with failure
            call_info = t.get("call", {})
            stage = "call"
            if call_info.get("outcome") != "failed":
                if t.get("setup", {}).get("outcome") == "failed":
                    call_info = t.get("setup", {})
                    stage = "setup"
                elif t.get("teardown", {}).get("outcome") == "failed":
                    call_info = t.get("teardown", {})
                    stage = "teardown"

            duration = call_info.get("duration", 0.0)
            crash = call_info.get("crash", {})
            crash_path = crash.get("path", "")
            crash_line = crash.get("lineno", 0)
            crash_msg = crash.get("message", "")
            category = categorize_failure(crash_msg)

            # Extract first meaningful line of error message
            msg_lines = [l.strip() for l in crash_msg.splitlines() if l.strip()]
            summary_msg = msg_lines[0] if msg_lines else "No error message"

            structured_failures.append({
                "index": count,
                "nodeid": nodeid,
                "test_name": test_name,
                "file": file_name,
                "stage": stage,
                "duration_seconds": duration,
                "crash_location": f"{crash_path}:{crash_line}",
                "category": category,
                "message": crash_msg,
            })

            print(f"  {Style.BOLD}[{count}] {Style.RED}FAILED:{Style.RESET} {Style.BOLD}{test_name}{Style.RESET}")
            print(f"      {Style.DIM}NodeID:{Style.RESET}    {nodeid}")
            print(f"      {Style.DIM}Location:{Style.RESET}  {crash_path}:{crash_line} (stage: {stage}, duration: {format_duration(duration)})")
            print(f"      {Style.YELLOW}Category:{Style.RESET}  {Style.BOLD}{category}{Style.RESET}")
            print(f"      {Style.RED}Error:{Style.RESET}     {summary_msg}")

            if len(msg_lines) > 1 and not show_full:
                print(f"                 {Style.DIM}{msg_lines[1][:100]}...{Style.RESET}")

            if show_full:
                longrepr = call_info.get("longrepr", "")
                if longrepr:
                    print(f"      {Style.DIM}Traceback / Details:{Style.RESET}")
                    for line in longrepr.splitlines():
                        print(f"        {Style.DIM}│{Style.RESET} {line}")
            print()

    return structured_failures


def analyze_warnings(warnings_list: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Analyze and deduplicate warnings."""
    print(f"\n{Style.BOLD}{Style.YELLOW}▶ WARNINGS ANALYSIS ({len(warnings_list)} total warnings){Style.RESET}")
    print("-" * 80)

    if not warnings_list:
        print(f"  {Style.GREEN}✔ Zero warnings captured during test execution!{Style.RESET}\n")
        return []

    # Deduplicate by (category, message_prefix, filename)
    grouped: Dict[str, Dict[str, Any]] = {}
    for w in warnings_list:
        cat = w.get("category", "Warning")
        msg = w.get("message", "").strip()
        fn = w.get("filename", "")
        ln = w.get("lineno", 0)

        # Truncate first line for key
        key = f"{cat}::{fn}::{msg[:80]}"
        if key not in grouped:
            grouped[key] = {
                "category": cat,
                "message": msg,
                "filename": fn,
                "lines": set(),
                "count": 0,
            }
        grouped[key]["lines"].add(ln)
        grouped[key]["count"] += 1

    structured_warnings = []
    idx = 0
    for key, info in sorted(grouped.items(), key=lambda x: -x[1]["count"]):
        idx += 1
        lines_str = ", ".join(str(l) for l in sorted(info["lines"]))
        msg_preview = info["message"].replace("\n", " ")
        if len(msg_preview) > 110:
            msg_preview = msg_preview[:110] + "..."

        structured_warnings.append({
            "category": info["category"],
            "count": info["count"],
            "filename": info["filename"],
            "lines": list(sorted(info["lines"])),
            "message": info["message"],
        })

        print(f"  {Style.BOLD}[{idx}] {Style.YELLOW}{info['category']}{Style.RESET} ({info['count']} occurrence{'s' if info['count'] > 1 else ''})")
        print(f"      {Style.DIM}Origin:{Style.RESET}   {info['filename']}:{lines_str}")
        print(f"      {Style.DIM}Detail:{Style.RESET}   {msg_preview}")
        print()

    return structured_warnings


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Deep report.json parser for pytest test suites and vulnerability discovery."
    )
    parser.add_argument(
        "report_file",
        nargs="?",
        default="report.json",
        help="Path to pytest json-report file (default: report.json)",
    )
    parser.add_argument(
        "-f", "--filter",
        dest="filter_pattern",
        help="Filter failed tests by test name or message substring",
    )
    parser.add_argument(
        "-v", "--full",
        action="store_true",
        help="Display full tracebacks and long error representations",
    )
    parser.add_argument(
        "--failures-only",
        action="store_true",
        help="Only display failure analysis (suppress warnings)",
    )
    parser.add_argument(
        "--warnings-only",
        action="store_true",
        help="Only display warnings analysis (suppress failures)",
    )
    parser.add_argument(
        "--no-color",
        action="store_true",
        help="Disable ANSI color codes",
    )
    parser.add_argument(
        "--json-out",
        dest="json_output_path",
        help="Export parsed failures and warnings summary into a clean JSON file",
    )

    args = parser.parse_args()

    # Handle color
    use_color = not args.no_color and sys.stdout.isatty()
    # Check NO_COLOR env var
    if os.environ.get("NO_COLOR"):
        use_color = False
    Style.strip_if_no_color(use_color)

    data = load_report(args.report_file)

    print_summary_header(data, args.report_file)

    parsed_failures = []
    parsed_warnings = []

    if not args.warnings_only:
        parsed_failures = analyze_failures(
            data.get("tests", []),
            filter_pattern=args.filter_pattern,
            show_full=args.full,
        )

    if not args.failures_only:
        parsed_warnings = analyze_warnings(data.get("warnings", []))

    if args.json_output_path:
        out_data = {
            "summary": data.get("summary", {}),
            "duration": data.get("duration", 0.0),
            "exitcode": data.get("exitcode", 0),
            "failures": parsed_failures,
            "warnings": parsed_warnings,
        }
        with open(args.json_output_path, "w", encoding="utf-8") as out_f:
            json.dump(out_data, out_f, indent=2)
        print(f"\n{Style.GREEN}✔ Parsed summary written to '{args.json_output_path}'{Style.RESET}")


if __name__ == "__main__":
    main()
